const { app, BrowserWindow, ipcMain, screen } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
app.setPath('userData', path.join(root, '.qa-data'));
const mouseStates = new Map();
const ignore = BrowserWindow.prototype.setIgnoreMouseEvents;
BrowserWindow.prototype.setIgnoreMouseEvents = function (value, options) {
  mouseStates.set(this.id, value);
  return ignore.call(this, value, options);
};
let cursor = { x: 0, y: 0 };
app.whenReady().then(() => { screen.getCursorScreenPoint = () => cursor; });
require('../out/main/index.js');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  await pause(1700);
  const windows = BrowserWindow.getAllWindows();
  const pet = windows.find(w => w.webContents.getURL().includes('mode=pet'));
  const hub = windows.find(w => w.webContents.getURL().includes('mode=hub'));
  assert.ok(pet && hub, 'both production windows created');
  assert.deepEqual(pet.getSize(), [260, 280]);
  const [x, y] = pet.getPosition();
  cursor = { x: x + 130, y: y + 130 };
  await pause(180);
  assert.equal(mouseStates.get(pet.id), false, 'near cursor enables interaction');
  cursor = { x: x - 200, y: y - 200 };
  await pause(180);
  assert.equal(mouseStates.get(pet.id), true, 'far cursor lets clicks through');
  ipcMain.emit('hub:toggle', {}, true);
  await pause(300);
  assert.deepEqual(hub.getSize(), [420, 650]);
  assert.equal(await hub.webContents.executeJavaScript('!!document.querySelector(".chat")'), true);
  await pet.webContents.executeJavaScript(`(() => {
    const b = document.querySelector('.mate-body');
    b.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, button: 0, clientX: 100, clientY: 130, screenX: 300, screenY: 330 }));
    window.dispatchEvent(new PointerEvent('pointerup', { bubbles: true, button: 0, screenX: 300, screenY: 330 }));
  })()`);
  await pause(200);
  assert.equal(await pet.webContents.executeJavaScript('!!document.querySelector(".mate-body.love")'), true, 'tap changes expression');
  await pet.webContents.executeJavaScript(`document.querySelector('.mate-body').dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))`);
  await pause(100);
  assert.equal(await pet.webContents.executeJavaScript('!!document.querySelector(".mate-body.dancing")'), true, 'double tap dances');
  const output = path.join(root, 'artifacts', 'desktop');
  await fs.mkdir(output, { recursive: true });
  await fs.writeFile(path.join(output, 'cine-desktop.png'), (await pet.webContents.capturePage()).toPNG());
  console.log('Desktop smoke passed: real main/preload, startup, click-through, hub resize, tap and dance.');
  app.quit();
}).catch(error => { console.error(error); app.exit(1); });
