const { app, BrowserWindow, ipcMain, screen, globalShortcut } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
app.setPath('userData', path.resolve(__dirname, '../.qa-data/click-through'));
let cursor = {x:0,y:0};
app.whenReady().then(()=>{screen.getCursorScreenPoint = () => cursor;});
const shortcuts = new Map();
const register = globalShortcut.register.bind(globalShortcut);
globalShortcut.register = (key, callback) => {shortcuts.set(key,callback);return register(key,callback);};
const ignored = new Map();
const ignore = BrowserWindow.prototype.setIgnoreMouseEvents;
BrowserWindow.prototype.setIgnoreMouseEvents = function(value, options){ignored.set(this.id,value);return ignore.call(this,value,options);};
require('../out/main/index.js');
const pause = ms => new Promise(resolve=>setTimeout(resolve,ms));
app.whenReady().then(async()=>{
  await pause(1300);
  const windows=BrowserWindow.getAllWindows();
  const pet=windows.find(w=>w.webContents.getURL().includes('mode=pet'));
  const hub=windows.find(w=>w.webContents.getURL().includes('mode=hub'));
  const run=code=>hub.webContents.executeJavaScript(code);
  await run(`localStorage.setItem('cinemate-settings-v1',JSON.stringify({voice:false,wander:false,stayPut:true}))`);
  hub.reload();await pause(700);
  ipcMain.emit('hub:toggle',{},true);
  await run(`[...document.querySelectorAll('.tabs button')].find(b=>b.textContent==='settings').click()`);
  const toggle=`[...document.querySelectorAll('label.check')].find(l=>l.textContent.includes('Allow clicks')).querySelector('input')`;
  const [x,y]=pet.getPosition();const [w,h]=pet.getSize();
  cursor={x:x+w/2,y:y+150};
  ipcMain.emit('mate:click-through',{},false);await pause(160);
  assert.equal(ignored.get(pet.id),false);
  for(let i=0;i<3;i++){
    await run(`${toggle}.click()`);await pause(180);
    assert.equal(await run('window.mate.getClickThrough()'),true);
    assert.equal(ignored.get(pet.id),true,'Body passes clicks through when enabled');
    cursor={x:x+w/2,y:y+h-15};await pause(160);
    assert.equal(ignored.get(pet.id),false,'Dock stays interactive for recovery');
    assert.equal(await run('window.mate.getClickThrough()'),true,'Cursor tracking does not change preference');
    await run(`${toggle}.click()`);await pause(150);
    cursor={x:x+w/2,y:y+150};await pause(150);
    assert.equal(ignored.get(pet.id),false,'Disabling click-through restores body interactions');
  }
  shortcuts.get('Control+Alt+M')();await pause(150);
  assert.equal(await run(`${toggle}.checked`),true,'Keyboard toggle updates Settings');
  shortcuts.get('Control+Alt+M')();await pause(150);
  assert.equal(await run(`${toggle}.checked`),false);
  const body=await pet.webContents.executeJavaScript(`(()=>{const b=document.querySelector('.mate-body').getBoundingClientRect();return{x:b.x+b.width/2,y:b.y+b.height/2}})()`);
  const before=pet.getPosition();
  pet.webContents.sendInputEvent({type:'mouseDown',x:Math.round(body.x),y:Math.round(body.y),button:'left',clickCount:1});
  await pause(120);
  pet.webContents.sendInputEvent({type:'mouseMove',x:Math.round(body.x-45),y:Math.round(body.y-35),button:'left'});
  await pause(160);
  pet.webContents.sendInputEvent({type:'mouseUp',x:Math.round(body.x-45),y:Math.round(body.y-35),button:'left',clickCount:1});
  await pause(120);
  assert.notDeepEqual(pet.getPosition(),before,'Actual pointer input drags Cine after disabling click-through');
  const area=screen.getPrimaryDisplay().workArea;
  ipcMain.emit('mate:move',{},area.x+200,area.y-250);await pause(300);
  await run(`(()=>{const c=new BroadcastChannel('cinemate-bubble');c.postMessage('A short message at the top of your screen.');c.close();})()`);
  await pause(150);
  const bubble=await pet.webContents.executeJavaScript(`(()=>{const b=document.querySelector('.bubble');const r=b.getBoundingClientRect();return{top:r.top,bottom:r.bottom,z:getComputedStyle(b).zIndex,edge:document.querySelector('.pet-stage').classList.contains('edge-top')}})()`);
  assert.equal(bubble.edge,true);
  assert.ok(pet.getPosition()[1]+bubble.top>=area.y,'Top-edge bubble stays on screen');
  assert.equal(bubble.z,'10','Bubble paints above character');
  const output=path.resolve(__dirname,'../artifacts/click-through');await fs.mkdir(output,{recursive:true});
  await fs.writeFile(path.join(output,'top-edge-bubble.png'),(await pet.webContents.capturePage()).toPNG());
  console.log(JSON.stringify({repeatedOnOff:true,dockRecovery:true,keyboardSettingsSync:true,realPointerDrag:true,topEdgeBubble: true}));
  app.quit();
}).catch(error=>{console.error(error);app.exit(1);});
