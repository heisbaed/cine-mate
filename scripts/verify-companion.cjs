const { app, BrowserWindow, ipcMain, screen } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const processes = require('node:child_process');
const spawn = processes.spawn;
const alerts = [];
processes.spawn = (...args) => {
  const child = spawn(...args);
  if (args[1]?.some(value => String(value).endsWith('timer-alert.ps1'))) {
    alerts.push(new Promise(resolve => child.once('close', resolve)));
  }
  return child;
};
app.setPath('userData', path.resolve(__dirname, '../.qa-data/features'));
require('../out/main/index.js');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const output = path.resolve(__dirname, '../artifacts/companion');
app.whenReady().then(async () => {
  await pause(1800);
  const windows = BrowserWindow.getAllWindows();
  const pet = windows.find(w => w.webContents.getURL().includes('mode=pet'));
  const hub = windows.find(w => w.webContents.getURL().includes('mode=hub'));
  assert.ok(pet && hub);
  const execute = hub.webContents.executeJavaScript.bind(hub.webContents);
  hub.webContents.executeJavaScript = (code, ...args) => {
    const result = execute(code, ...args);
    if (code.includes('const context = new AudioContext()')) alerts.push(result.then(() => 0));
    return result;
  };
  ipcMain.removeHandler('mate:now-playing');
  ipcMain.handle('mate:now-playing', () => null);
  assert.equal(hub.isVisible(), false, 'collapsed chat has no floating native window');
  assert.equal(await hub.webContents.executeJavaScript('!!document.querySelector(".hub-fab")'), false);
  await pet.webContents.executeJavaScript('document.querySelector(".pet-chat").click()');
  await pause(250);
  assert.equal(hub.isVisible(), true, 'message icon opens chat');
  await pet.webContents.executeJavaScript('document.querySelector(".pet-chat").click()');
  await pause(150);
  assert.equal(hub.isVisible(), false, 'message icon closes chat');
  await fs.mkdir(output, { recursive: true });
  const emit = async (channel, payload) => {
    await hub.webContents.executeJavaScript(`(() => { const c = new BroadcastChannel(${JSON.stringify(channel)}); c.postMessage(${JSON.stringify(payload)}); c.close(); })()`);
    await pause(150);
  };
  await emit('cinemate-config', { wander: false, size: 'M', pet: 'robot' });
  await emit('cinemate-now', { title: 'Music test', artist: 'Cine', playing: true });
  assert.equal(await pet.webContents.executeJavaScript('document.querySelectorAll(".cine-headphones").length'), 2);
  await fs.writeFile(path.join(output, 'music-headphones.png'), (await pet.webContents.capturePage()).toPNG());
  await emit('cinemate-now', { title: 'Music test', playing: false });
  assert.equal(await pet.webContents.executeJavaScript('document.querySelectorAll(".cine-headphones").length'), 0);
  await emit('cinemate-bubble', 'Hello!');
  const shortWidth = await pet.webContents.executeJavaScript('document.querySelector(".bubble").getBoundingClientRect().width');
  assert.ok(shortWidth < 100, 'short text uses a small bubble');
  await emit('cinemate-bubble', 'A little reminder for you. Take a breath and stretch your shoulders.');
  const box = await pet.webContents.executeJavaScript('(() => { const r = document.querySelector(".bubble").getBoundingClientRect(); return {w:r.width,h:r.height}; })()');
  assert.ok(box.w <= 176 && box.h <= 38, 'bubble stays compact and limited to two lines');
  const area = screen.getPrimaryDisplay().workArea;
  ipcMain.emit('mate:move', {}, area.x + 200, area.y - 100);
  await pause(200);
  const inset = await pet.webContents.executeJavaScript('Math.max(0,document.querySelector(".mate-body").getBoundingClientRect().top - 12)');
  assert.ok(Math.abs(pet.getPosition()[1] - Math.round(area.y - inset)) <= 1, 'top movement follows actual character size within Windows DPI rounding');
  await pause(200);
  assert.equal(await pet.webContents.executeJavaScript('!!document.querySelector(".edge-top")'), true);
  ipcMain.emit('mate:move', {}, area.x + 200, area.y + 100);
  ipcMain.removeHandler('mate:now-playing');
  ipcMain.handle('mate:now-playing', () => ({ title: 'Music during countdown', artist: 'Cine', playing: true }));
  await hub.webContents.executeJavaScript(`localStorage.setItem('cinemate-settings-v1', JSON.stringify({voice:false, wander:false, wakeListening:false}))`);
  await hub.reload();
  await pause(1000);
  ipcMain.emit('hub:toggle', {}, false);
  ipcMain.emit('hub:toggle', {}, true);
  await pause(200);
  const command = async text => {
    await hub.webContents.executeJavaScript(`(() => { const input=document.querySelector('form input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input, ${JSON.stringify(text)}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await pause(80);
    await hub.webContents.executeJavaScript('document.querySelector("form").requestSubmit()');
    await pause(400);
  };
  await command('set a timer for 5 seconds');
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display")?.textContent || ""'), /TIMER00:0[45]/);
  await fs.writeFile(path.join(output, 'face-timer.png'), (await pet.webContents.capturePage()).toPNG());
  ipcMain.emit('hub:toggle', {}, false);
  await pause(5500);
  assert.equal(alerts.length, 1, 'timer chimes exactly once with voice off and chat hidden');
  assert.equal(await alerts[0], 0, 'native timer chime plays successfully');
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display")?.textContent || ""'), /DONE00:00/);
  await pause(6500);
  assert.equal(await pet.webContents.executeJavaScript('!!document.querySelector(".cine-face-display")'), false, 'normal face returns');
  ipcMain.emit('hub:toggle', {}, true);
  await pause(150);
  await command('set a timer for 5 seconds');
  await command('cancel timer');
  await pause(5500);
  assert.equal(alerts.length, 1, 'cancelled timer does not chime');
  assert.equal(await pet.webContents.executeJavaScript('!!document.querySelector(".cine-face-display")'), false);
  console.log('Companion verification passed: face countdown, completion, sound with voice off, cancellation, playback-state headphones, compact bubble, upward movement, and chat icon toggle.');
  app.quit();
}).catch(error => { console.error(error); app.exit(1); });
