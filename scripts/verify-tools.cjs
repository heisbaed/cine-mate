const { app, BrowserWindow, ipcMain, globalShortcut } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
app.setPath('userData', path.resolve(__dirname, '../.qa-data/tools'));
require('../out/main/index.js');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  await pause(1500);
  const windows = BrowserWindow.getAllWindows();
  const pet = windows.find(w => w.webContents.getURL().includes('mode=pet'));
  const hub = windows.find(w => w.webContents.getURL().includes('mode=hub'));
  const run = code => hub.webContents.executeJavaScript(code);
  await run(`localStorage.clear()`);
  hub.reload(); await pause(1200);
  ipcMain.emit('hub:toggle', {}, true); await pause(200);
  const tab = async name => { await run(`[...document.querySelectorAll('.tabs button')].find(b => b.textContent === ${JSON.stringify(name)}).click()`); await pause(200); };
  const button = async name => { await run(`[...document.querySelectorAll('button')].find(b => b.textContent === ${JSON.stringify(name)}).click()`); await pause(150); };
  const input = async (label, value) => {
    await run(`(() => { const el = document.querySelector('[aria-label="${label}"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)}); el.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await pause(60);
  };
  const checkbox = async text => { await run(`[...document.querySelectorAll('label.check')].find(l => l.textContent.includes(${JSON.stringify(text)})).querySelector('input').click()`); await pause(200); };
  const submit = async label => { await run(`document.querySelector('[aria-label="${label}"]').closest('form').requestSubmit()`); await pause(120); };
  await tab('tools');
  await run(`Object.defineProperty(navigator, 'clipboard', { configurable:true, value: { readText:async ()=>'QA clip', writeText:async value=>{window.__copied=value;} } });`);
  await button('Save clipboard');
  assert.equal(await run('document.querySelector(".clip-text").textContent'), 'QA clip');
  await run('document.querySelector(".clip-text").click()');
  await pause(50);
  assert.equal(await run('window.__copied'), 'QA clip');
  await input('New note', 'Remember the red scarf'); await submit('New note');
  await input('Search notes', 'red scarf');
  assert.ok(await run('document.body.innerText.includes("Remember the red scarf")'));
  await input('New daily goal', 'Finish one small thing'); await submit('New daily goal');
  await checkbox('Finish one small thing');
  assert.ok(await run('!!document.querySelector(".goal-done")'));
  await button('Start maths game');
  const challenge = await run(`document.querySelector('[aria-label="Maths answer"]').closest('label').textContent`);
  const parts = challenge.match(/(\d+)\s*([×+])\s*(\d+)/);
  await input('Maths answer', String(parts[2] === '×' ? +parts[1] * +parts[3] : +parts[1] + +parts[3]));
  await submit('Maths answer');
  assert.ok(await run('document.body.innerText.includes("Correct!")'));
  await checkbox('Show local time');
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display")?.textContent || ""'), /LOCAL TIME/);
  await button('Start stopwatch'); await pause(1200);
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display")?.textContent || ""'), /STOPWATCH00:01/);
  await button('Pause stopwatch');
  const paused = await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display").textContent');
  await pause(1100);
  assert.equal(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display").textContent'), paused);
  await button('Reset stopwatch');
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display").textContent'), /LOCAL TIME/);
  await button('1 min');
  await button('Pause timer');
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-face-display").textContent'), /PAUSED/);
  await button('+1 min');
  assert.match(await pet.webContents.executeJavaScript('document.querySelector(".cine-display-value").textContent'), /0[12]:/);
  await button('Resume timer');
  await button('Cancel timer');
  const output = path.resolve(__dirname, '../artifacts/companion'); await fs.mkdir(output, { recursive: true });
  await run('document.querySelector(".tools-panel").scrollTop = 0');
  await fs.writeFile(path.join(output, 'tools.png'), (await hub.webContents.capturePage()).toPNG());
  await tab('settings');
  const accessories = await run('[...document.querySelectorAll(".accessory-grid button")].map(b => b.textContent)');
  assert.equal(accessories.length, 11, 'ten accessories plus none');
  for (const name of accessories) {
    await button(name);
    const choice = await run('JSON.parse(localStorage.getItem("cinemate-settings-v1")).accessory');
    assert.ok(await pet.webContents.executeJavaScript(`!!document.querySelector('.accessory-${choice}')`));
  }
  await button('Hoverboard');
  await fs.writeFile(path.join(output, 'hoverboard.png'), (await pet.webContents.capturePage()).toPNG());
  await checkbox('Softer glow at night');
  await checkbox('Cinema mode');
  assert.ok(globalShortcut.isRegistered('Control+Alt+C'));
  assert.ok(globalShortcut.isRegistered('Control+Alt+H'));
  await tab('tools');
  assert.ok(await run('document.body.innerText.includes("Remember the red scarf")'));
  assert.ok(await run('!!document.querySelector(".goal-done")'));
  console.log('Tools verification passed: clipboard capture/copy, saved searchable notes, daily goals, maths game, face clock, stopwatch, timer controls, ten accessory choices, settings, shortcuts, and persistence.');
  app.quit();
}).catch(error => { console.error(error); app.exit(1); });
